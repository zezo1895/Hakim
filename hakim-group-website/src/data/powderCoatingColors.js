const CUSTOM_WOOD_STORAGE_KEY = "hakim_custom_wood_finishes_v1";

export function getCustomWoodFinishes() {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem(CUSTOM_WOOD_STORAGE_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

export function saveCustomWoodFinish(finish) {
  if (typeof window === "undefined") return [];
  const current = getCustomWoodFinishes();
  const index = current.findIndex((f) => f.id === finish.id || f.code === finish.code);
  let updated;
  if (index >= 0) {
    updated = [...current];
    updated[index] = finish;
  } else {
    updated = [finish, ...current];
  }
  try {
    localStorage.setItem(CUSTOM_WOOD_STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error("Failed to save custom wood finish:", e);
  }
  window.dispatchEvent(new CustomEvent("hakim_finishes_updated", { detail: updated }));
  return updated;
}

export function deleteCustomWoodFinish(id) {
  if (typeof window === "undefined") return [];
  const current = getCustomWoodFinishes();
  const updated = current.filter((f) => f.id !== id && f.code !== id);
  try {
    localStorage.setItem(CUSTOM_WOOD_STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error("Failed to delete custom wood finish:", e);
  }
  window.dispatchEvent(new CustomEvent("hakim_finishes_updated", { detail: updated }));
  return updated;
}

